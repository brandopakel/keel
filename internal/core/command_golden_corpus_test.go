// The corpus, a session per case, by family. Each case starts on an empty
// engine with the log open; see command_golden_test.go for how a case runs
// and how its fixture is held. A case holds the paths of one command, or of
// a few that share their state: every reply shape in both protocols, every
// option, and every error the handlers give, in the order Redis gives them.
// Replies that are not the same from run to run carry a normalizer (norm).
var commandGoldenCorpus = concatGolden(goldenStrings, goldenKeys, goldenHashes, goldenLists, goldenSets, goldenSortedSets,
	goldenGeo, goldenHLL, goldenBloom, goldenCuckoo, goldenSketches, goldenServer, goldenTransactions, goldenDump,
	goldenReplication, goldenRefusals)

func concatGolden(families ...[]commandGoldenCase) []commandGoldenCase {
	var out []commandGoldenCase
	for _, f := range families {
		out = append(out, f...)
	}
	return out
}

// hoursS and hoursMs are a relative TTL of n hours in seconds and in
// milliseconds: whole hours, so that the instant it is logged as normalizes.
func hoursS(n int) string  { return hours(n, time.Second) }
func hoursMs(n int) string { return hours(n, time.Millisecond) }

