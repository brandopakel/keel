// arityGoldenSteps sends every command with one argument too few, and, for
// a fixed count, one too many, as the error-parity harness does.
func arityGoldenSteps() []goldenStep {
	var names []string
	for name := range commandArity {
		if !connectionCommands[name] {
			names = append(names, name)
		}
	}
	slices.Sort(names)
	var steps []goldenStep
	for _, name := range names {
		arity := commandArity[name]
		counts := []int{-arity - 1}
		if arity >= 0 {
			counts = []int{arity - 1, arity + 1}
		}
		for _, count := range counts {
			if count < 1 {
				continue
			}
			args := []string{name}
			if count%2 == 1 {
				args[0] = strings.ToLower(name)
			}
			for i := 1; i < count; i++ {
				args = append(args, "1")
			}
			steps = append(steps, send(args...))
		}
	}
	return steps
}
