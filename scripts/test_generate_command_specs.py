import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

spec = importlib.util.spec_from_file_location('generate_command_specs', Path(__file__).with_name('generate-command-specs.py'))
gcs = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gcs)

CHECK = '''package core

var commandArity = map[string]int{
	"PING": -1, "GET": 2,
	"MSET": -3, "KEEL.DUMP": 2,
	"CLIENT": -2,
}

var (
	clientSubcommands = []subcommand{{"id", 2}, {"help", 2}}
	containerCommands = map[string][]subcommand{"CLIENT": clientSubcommands}
)
'''

GET = {"GET": {"summary": "text that is not copied", "arity": 2, "group": "string", "command_flags": ["READONLY", "FAST"],
               "acl_categories": ["STRING"], "key_specs": [{"flags": ["RO", "ACCESS"], "begin_search": {"index": {"pos": 1}},
                                                            "find_keys": {"range": {"lastkey": 0, "step": 1, "limit": 0}}}]}}
MSET = {"MSET": {"arity": -3, "group": "string", "command_flags": ["WRITE", "DENYOOM"], "acl_categories": ["STRING"],
                 "key_specs": [{"flags": ["OW", "UPDATE"], "begin_search": {"index": {"pos": 1}},
                                "find_keys": {"range": {"lastkey": -1, "step": 2, "limit": 0}}}]}}
CLIENT_ID = {"ID": {"container": "CLIENT", "arity": 2, "group": "connection", "command_flags": ["NOSCRIPT"], "acl_categories": ["CONNECTION"]}}
PING = {"PING": {"arity": -1, "group": "connection", "command_flags": ["FAST"], "acl_categories": ["CONNECTION"]}}
KEYNUM = {"X": {"arity": -2, "group": "generic", "key_specs": [{"begin_search": {"keyword": {"keyword": "KEYS", "startfrom": 1}},
                                                               "find_keys": {"keynum": {"keynumidx": 0, "firstkey": 1, "step": 1}}}]}}


class Commands(unittest.TestCase):
    def test_reads_names_and_subcommands(self):
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp) / 'command_check.go'
            source.write_text(CHECK)
            self.assertEqual(gcs.keel_commands(source),
                             [('PING', None), ('GET', None), ('MSET', None), ('KEEL.DUMP', None), ('CLIENT', None),
                              ('CLIENT', 'ID'), ('CLIENT', 'HELP')])


    def test_reads_a_subcommand_literal_over_several_lines(self):
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp) / 'command_check.go'
            source.write_text(CHECK.replace('clientSubcommands = []subcommand{{"id", 2}, {"help", 2}}',
                                            'clientSubcommands = []subcommand{\n\t\t{"id", 2},\n\t\t{"help", 2},\n\t}'))
            self.assertEqual(gcs.keel_commands(source)[-2:], [('CLIENT', 'ID'), ('CLIENT', 'HELP')])

    def test_refuses_a_subcommand_literal_it_cannot_read(self):
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp) / 'command_check.go'
            source.write_text(CHECK.replace('clientSubcommands = []subcommand{{"id", 2}, {"help", 2}}',
                                            'clientSubcommands = []subcommand{{"id", 2}, {helpName, 2}}'))
            with self.assertRaises(ValueError):
                gcs.keel_commands(source)


class Specs(unittest.TestCase):
    def test_key_spec_forms(self):
        ks = gcs.key_spec(GET['GET']['key_specs'][0])
        self.assertEqual(ks['begin'], ('index', 1, '', 0))
        self.assertEqual(ks['find'], ('range', dict(lastKey=0, step=1, limit=0)))
        ks = gcs.key_spec(KEYNUM['X']['key_specs'][0])
        self.assertEqual(ks['begin'], ('keyword', 0, 'KEYS', 1))
        self.assertEqual(ks['find'], ('keynum', dict(keynumIdx=0, firstKey=1, step=1)))
        self.assertEqual(ks['flags'], [])

    def test_collect_and_render(self):
        with tempfile.TemporaryDirectory() as tmp:
            commands = Path(tmp) / 'src' / 'commands'
            commands.mkdir(parents=True)
            for name, body in (('get', GET), ('mset', MSET), ('client-id', CLIENT_ID), ('ping', PING)):
                (commands / f'{name}.json').write_text(json.dumps(body))
            specs = gcs.collect(tmp, [('PING', None), ('GET', None), ('MSET', None), ('KEEL.DUMP', None),
                                      ('CLIENT', 'ID'), ('CLIENT', 'HELP')])
            self.assertEqual(sorted(specs), ['CLIENT|ID', 'GET', 'MSET', 'PING'], 'a name Redis has no spec for is left out')
            self.assertEqual(specs['MSET']['keys'][0]['find'], ('range', dict(lastKey=-1, step=2, limit=0)))
            text = gcs.render(specs)
            self.assertIn('// Code generated by scripts/generate-command-specs.py', text)
            self.assertIn('{name: "CLIENT|ID", spec: commandSpec{arity: 2, group: "connection", flags: []string{"NOSCRIPT"}, '
                          'acl: []string{"CONNECTION"}, keys: nil}},', text)
            self.assertIn('find: keyFind{kind: "range", lastKey: -1, step: 2, limit: 0}}}}}', text)
            self.assertIn('var redisCommandSpecTable = []namedCommandSpec{', text, 'a slice, laid out as data')
            self.assertNotIn('map[string]commandSpec', text, 'no map literal, whose initializer is code')
            names = [line.split('"')[1] for line in text.splitlines() if line.startswith('\t{name: ') and 'spec: commandSpec' in line]
            self.assertEqual(names, sorted(names), 'in name order')
            self.assertNotIn('text that is not copied', text)
            with self.assertRaises(ValueError):
                gcs.collect(Path(tmp) / 'nowhere', [('GET', None)])

    def test_facts_for_command_info_and_docs_and_no_text(self):
        set_spec = {"SET": {"summary": "text that is not copied", "complexity": "O(1), not copied", "since": "1.0.0",
                            "arity": -3, "group": "string", "get_keys_function": "setGetKeys",
                            "history": [["2.6.12", "text that is not copied"]], "command_tips": ["NONDETERMINISTIC_OUTPUT"],
                            "command_flags": ["WRITE"], "acl_categories": ["STRING"],
                            "key_specs": [{"notes": "text that is not copied", "flags": ["RW"], "begin_search": {"index": {"pos": 1}},
                                           "find_keys": {"range": {"lastkey": 0, "step": 1, "limit": 0}}}],
                            "arguments": [{"name": "key", "type": "key", "key_spec_index": 0},
                                          {"name": "condition", "type": "oneof", "optional": True, "since": "2.6.12",
                                           "arguments": [{"name": "nx", "type": "pure-token", "token": "nx"},
                                                         {"name": "xx", "type": "pure-token", "token": "XX",
                                                          "summary": "text that is not copied"}]},
                                          {"name": "Seconds", "type": "integer", "display": "SECONDS", "multiple": True,
                                           "multiple_token": True, "deprecated_since": "7.0.0"}]}}
        with tempfile.TemporaryDirectory() as tmp:
            commands = Path(tmp) / 'src' / 'commands'
            commands.mkdir(parents=True)
            (commands / 'set.json').write_text(json.dumps(set_spec))
            specs = gcs.collect(tmp, [('SET', None)])
            text = gcs.render(specs)
        s = specs['SET']
        self.assertEqual((s['tips'], s['since'], s['getkeys']), (['nondeterministic_output'], '1.0.0', 'setGetKeys'))
        self.assertEqual(s['args'][1]['args'][0]['token'], 'NX', 'tokens in upper case, as Redis writes them')
        self.assertEqual(s['args'][2], {'name': 'seconds', 'type': 'integer', 'display': 'seconds', 'key_spec': -1, 'token': '',
                                        'since': '', 'deprecated_since': '7.0.0', 'flags': ['multiple', 'multiple_token'], 'args': []})
        self.assertIn('\t{name: "SET", tips: []string{"nondeterministic_output"}, since: "1.0.0", args: ', text)
        self.assertIn('getKeys: "setGetKeys"},', text)
        self.assertIn('{name: "SET", spec: commandSpec{arity: -3, group: "string", flags: []string{"WRITE"}, acl: []string{"STRING"}, keys: ', text)
        self.assertIn('tips: []string{"nondeterministic_output"}', text)
        self.assertIn('{name: "condition", typ: "oneof", keySpec: -1, since: "2.6.12", flags: []string{"optional"}, args: []commandArg{', text)
        self.assertNotIn('not copied', text)


if __name__ == '__main__':
    unittest.main()
